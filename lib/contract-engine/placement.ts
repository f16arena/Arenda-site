export type AnnexPart =
  | { kind: "p"; text: string }
  | { kind: "item"; text: string } // строка-перечисление с отступом
  | { kind: "table"; head: string[]; rows: string[][] }
  | { kind: "frame"; caption: string } // пустое поле под схему

export interface AnnexDoc {
  no: number
  title: string
  subtitle: string
  parts: AnnexPart[]
}

const BLANK = "____________________________"
function fill(v: string | undefined | null, blank = BLANK): string {
  return v && v.trim() ? v.trim() : blank
}

/**
 * Приложения договора на размещение — ОДИН источник для текста подписи
 * (render.ts), DOCX (docx.ts) и превью (конструктор, карточка договора).
 */
export function placementAnnexes(s: ContractState): AnnexDoc[] {
  const fam = placementFamily(s)
  if (!fam) return []
  const t = terms(s, fam)
  const eq = fam === "equipment"
  const an = placementAnnexNumbers(s)
  const p = s.premises
  const out: AnnexDoc[] = []
  const where = `${p.buildingAddress || "________"}${t.placeDescription ? ", " + t.placeDescription : p.placement ? ", " + p.placement : ""}`

  if (an.act) {
    const parts: AnnexPart[] = []
    parts.push({ kind: "p", text: `${s.meta.city}    ${dateLong(s.meta.contractDate)}` })
    parts.push({ kind: "p", text: `${s.landlord.name || "Арендодатель"} (Арендодатель) и ${s.tenant.name || "Арендатор"} (Арендатор) составили настоящий Акт о нижеследующем:` })
    parts.push({
      kind: "p",
      text: `1. Арендодатель передал, а Арендатор принял ${eq ? "часть нежилого помещения" : "часть земельного участка"} (Место) по адресу: ${where}, площадью ${t.placeAreaSqm ? num(t.placeAreaSqm) : "____"} кв. м${an.scheme ? `, в границах согласно Схеме размещения (Приложение № ${an.scheme})` : ""}.`,
    })
    parts.push({ kind: "p", text: `2. Состояние ${eq ? "Места (пол, стены, отделка в границах Места)" : "Места (покрытие, благоустройство, озеленение)"} на момент передачи: ${fill(t.placeCondition)}.` })
    if (t.electricity === "none") {
      parts.push({ kind: "p", text: `3. Электроснабжение: ${eq ? "Оборудование" : "Объект"} к электрическим сетям не подключается.` })
    } else {
      const reading = t.electricity === "meter" ? `; показания прибора учёта на момент передачи: ${fill(s.handoverAct?.meterElectricity, "________")} кВт·ч` : `; оплата — фиксированная, ${t.electricityFixed ? money(t.electricityFixed) : "____"} в месяц`
      parts.push({
        kind: "p",
        text: `3. Электроснабжение: точка подключения — ${fill(t.connectionPoint)}${t.powerLimitKw ? `; разрешённая мощность — ${num(t.powerLimitKw)} кВт` : ""}${reading}.`,
      })
    }
    parts.push({ kind: "p", text: eq ? "4. Перечень размещаемого Оборудования:" : "4. Характеристики размещаемого Объекта:" })
    const rows = (t.equipment.length ? t.equipment : [{ name: "", model: "", serial: "", qty: 0, size: "", powerKw: 0 }]).map((e, i) => [
      String(i + 1),
      fill(e.name, "________"),
      fill(e.model, "—"),
      fill(e.serial, "—"),
      e.qty ? String(e.qty) : "____",
      fill(e.size, "____"),
      e.powerKw ? num(e.powerKw) : "—",
    ])
    parts.push({ kind: "table", head: ["№", "Наименование", "Модель", "Заводской №", "Кол-во", "Габариты", "Мощность, кВт"], rows })
    parts.push({ kind: "p", text: `5. ${eq ? "Оборудование" : "Объект"} является собственностью Арендатора; Арендодатель его на хранение не принимает и за его сохранность не отвечает, кроме случаев, прямо предусмотренных Договором.` })
    parts.push({ kind: "p", text: "6. Место соответствует условиям Договора, претензий по его состоянию у Арендатора нет." })
    out.push({ no: an.act, title: "АКТ", subtitle: ACT_SUBTITLE[fam], parts })
  }

  if (an.scheme) {
    const parts: AnnexPart[] = []
    parts.push({ kind: "p", text: `Место: ${where}, площадью ${t.placeAreaSqm ? num(t.placeAreaSqm) : "____"} кв. м.` })
    parts.push({
      kind: "p",
      text: `На схеме Стороны обозначают границы Места, расположение ${eq ? "Оборудования" : "Объекта"}${t.electricity !== "none" ? ", точку подключения к электросети" : ""}${eq ? " и эвакуационные проходы, которые не должны загромождаться" : " и пути подъезда"}. Схема подписывается обеими Сторонами и является неотъемлемой частью Договора.`,
    })
    parts.push({ kind: "frame", caption: "Схема размещения" })
    out.push({ no: an.scheme, title: "СХЕМА", subtitle: eq ? "размещения Оборудования" : "размещения Объекта на земельном участке", parts })
  }
  return out
}

/** Текстовая форма приложений (для детерминированной строки подписи). */
export function placementAnnexesText(s: ContractState): string[] {
  const out: string[] = []
  for (const a of placementAnnexes(s)) {
    out.push("", "—".repeat(40))
    out.push(`Приложение № ${a.no} к Договору № ${s.meta.contractNumber || "____"} от ${dateLong(s.meta.contractDate)}`)
    out.push("", a.title, a.subtitle, "")
    for (const part of a.parts) {
      if (part.kind === "p") out.push(part.text)
      else if (part.kind === "item") out.push(`    — ${part.text}`)
      else if (part.kind === "table") {
        out.push(`    ${part.head.join(" | ")}`)
        for (const r of part.rows) out.push(`    ${r.join(" | ")}`)
      } else out.push(`[${part.caption}]`)
    }
  }
  return out
}

/** Замечания конструктора для договора на размещение. */
export function validatePlacement(s: ContractState): { hard: string[]; soft: string[] } {
  const fam = placementFamily(s)
  if (!fam) return { hard: [], soft: [] }
  const t = terms(s, fam)
  const hard: string[] = []
  const soft: string[] = []
  if (!t.placeAreaSqm) soft.push("Не указана площадь Места — в договоре останется прочерк.")
  if (!t.placeDescription.trim() && !s.premises.placement.trim()) soft.push("Не описано, где именно находится Место (например, «холл 1 этажа, справа от входа»).")
  if (t.equipment.length === 0) soft.push(fam === "equipment" ? "Перечень оборудования пуст — без него неясно, что именно разрешено разместить." : "Не описан объект (киоск, контейнер) — укажите его в перечне.")
  if (t.electricity === "fixed" && !t.electricityFixed) hard.push("Электроэнергия фиксированной платой: укажите сумму в месяц.")
  if (fam === "territory" && !t.landDocument.trim()) soft.push("Не указан документ на земельный участок (акт на право собственности или договор аренды земли).")
  return { hard, soft }
}
