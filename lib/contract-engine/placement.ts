// Договоры на размещение: оборудование в здании и временный объект на территории.
//
// ADR: у договора аренды помещения и у договора на размещение разный предмет —
// поэтому не «помещение с заменённым словом», а свой набор пунктов и приложений.
// Семейство определяется блоком s.placement (его нет у ранее подписанных
// договоров → они рендерятся прежним текстом, байт-в-байт как при подписании).
//
// Юридическая конструкция: аренда части имущества (ГК РК, имущественный наём).
// Оборудование — в здании: часть нежилого помещения (Место); территория — часть
// земельного участка под ВРЕМЕННОЕ (некапитальное) сооружение. Условия написаны
// в интересах Арендодателя (пользователь платформы — собственник объекта).
// Текст — основа; перед массовым использованием его стоит показать юристу.

